"""Export models/final.keras for the firmware.

Outputs:
    models/model_int8.tflite          (int8 reference, used by evaluate.py)
  ESP32 (float32 engine, verified against Keras before writing):
    firmware/src/model_weights_f32.h
    firmware/src/norm_params.h        (normalisation + window constants + class names)
  STM32 (same float32 engine):
    firmware_stm32/src/stm32_model_weights_f32.h
    firmware_stm32/src/stm32_norm_params.h
"""
import os
import tempfile

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np
import tensorflow as tf

import config as C
from common import load_json, load_windows, normalize, select


def convert(model, rep_X):
    # Keras 3: go through a SavedModel with a fixed batch of 1 so variables are
    # frozen to constants (needed for int8 calibration).
    with tempfile.TemporaryDirectory() as tmp:
        model.export(tmp, input_signature=[
            tf.TensorSpec([1, C.WIN, 1, C.N_CH], tf.float32)], verbose=False)
        conv = tf.lite.TFLiteConverter.from_saved_model(tmp)
        return _quantize(conv, rep_X)


def _quantize(conv, rep_X):
    conv.optimizations = [tf.lite.Optimize.DEFAULT]

    def rep():
        for i in range(len(rep_X)):
            yield [rep_X[i:i + 1]]

    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    # The ESP32 TFLite-Micro kernels reject per-channel FULLY_CONNECTED weights
    # ("FullyConnected per-channel quantization not yet supported").
    conv._experimental_disable_per_channel_quantization_for_dense_layers = True
    return conv.convert()


def write_norm_header(norm, path):
    f = lambda v: ", ".join(f"{x:.6f}f" for x in v)
    names = ", ".join(f'"{c}"' for c in C.CLASSES)
    path.write_text(
        "// Generated by ml/export.py -- do not edit.\n"
        "#pragma once\n\n"
        f"constexpr int kWin = {C.WIN};\n"
        f"constexpr int kPre = {C.PRE};\n"
        f"constexpr int kChannels = {C.N_CH};\n"
        f"constexpr int kNumClasses = {len(C.CLASSES)};\n"
        f"constexpr int kFallIdx = {C.FALL_IDX};\n"
        f"constexpr float kNormMean[kChannels] = {{{f(norm['mean'])}}};\n"
        f"constexpr float kNormStd[kChannels] = {{{f(norm['std'])}}};\n"
        f"static const char* const kClassNames[kNumClasses] = {{{names}}};\n")


def main():
    model = tf.keras.models.load_model(C.MODELS_DIR / "final.keras")
    norm = load_json(C.MODELS_DIR / "norm.json")
    splits = load_json(C.MODELS_DIR / "splits.json")
    d = load_windows()

    tr = select(d, splits["train"], eval_only=True)
    rng = np.random.default_rng(0)
    idx = rng.choice(np.flatnonzero(tr), min(500, tr.sum()), replace=False)
    rep_X = normalize(d["X"][idx], norm)

    tfl = convert(model, rep_X)
    out = C.MODELS_DIR / "model_int8.tflite"
    out.write_bytes(tfl)
    print(f"Saved {out} ({len(tfl) / 1024:.1f} KB)")

    # ---- Float32 engine (ESP32 firmware/src/model.cpp and STM32
    # stm32_model_cnn_f32.cpp share the same loops). The ESP32 TFLite-Micro
    # build has no ESP-NN kernels and took ~1 s per window; this takes ms.
    layers = fold_layers(model)
    check_X = normalize(d["X"][idx[:200]], norm)
    ref = model.predict(check_X, verbose=0)
    mine = np.stack([c_forward(x, layers) for x in check_X])
    err = float(np.abs(ref - mine).max())
    print(f"float engine vs Keras: max |diff| = {err:.2e}")
    if err > 1e-3:
        raise SystemExit("float engine mismatch -- not writing firmware headers")

    C.FIRMWARE_SRC.mkdir(parents=True, exist_ok=True)
    write_f32_header(layers, C.FIRMWARE_SRC / "model_weights_f32.h")
    write_norm_header(norm, C.FIRMWARE_SRC / "norm_params.h")
    print(f"Wrote {C.FIRMWARE_SRC / 'model_weights_f32.h'} and norm_params.h")

    C.FIRMWARE_STM32_SRC.mkdir(parents=True, exist_ok=True)
    write_f32_header(layers, C.FIRMWARE_STM32_SRC / "stm32_model_weights_f32.h")
    write_norm_header(norm, C.FIRMWARE_STM32_SRC / "stm32_norm_params.h")
    print(f"Wrote {C.FIRMWARE_STM32_SRC / 'stm32_model_weights_f32.h'} and stm32_norm_params.h")


# ------------------------------------------------------------------ STM32
def fold_layers(model):
    """Return conv layers (BN folded) and dense layers in C layouts:
    conv w [cout][k][cin], dense w [out][in]."""
    L = tf.keras.layers
    convs, denses, pending = [], [], None
    for layer in model.layers:
        if isinstance(layer, L.Conv2D):
            pending = layer
        elif isinstance(layer, L.BatchNormalization) and pending is not None:
            k = pending.get_weights()[0]            # (k, 1, cin, cout)
            gamma, beta, mean, var = layer.get_weights()
            scale = gamma / np.sqrt(var + layer.epsilon)
            w = (k[:, 0] * scale).transpose(2, 0, 1)  # -> (cout, k, cin)
            b = beta - mean * scale
            convs.append((w.astype(np.float32), b.astype(np.float32)))
            pending = None
        elif isinstance(layer, L.Dense):
            w, b = layer.get_weights()               # (in, out)
            denses.append((w.T.astype(np.float32), b.astype(np.float32)))
    if len(convs) != 3 or len(denses) != 2:
        raise SystemExit("stm32_model_cnn_f32.cpp expects 3 Conv+BN blocks and 2 Dense "
                         "layers; update it if you change the architecture")
    return {"convs": convs, "denses": denses}


def c_forward(x, layers):
    """NumPy mirror of stm32_model_cnn_f32.cpp (x: (WIN, 1, 6) normalised)."""
    h = x[:, 0, :].astype(np.float32)
    for i, (w, b) in enumerate(layers["convs"]):
        cout, k, cin = w.shape
        half = (k - 1) // 2
        pad = np.pad(h, ((half, half), (0, 0)))
        cols = np.stack([pad[j:j + len(h)] for j in range(k)], axis=1)  # (L,k,cin)
        h = np.maximum(np.einsum("tkc,okc->to", cols, w) + b, 0)
        if i < 2:
            h = np.maximum(h[0:len(h) // 2 * 2:2], h[1:len(h) // 2 * 2:2])
    h = h.mean(axis=0)
    (w1, b1), (w2, b2) = layers["denses"]
    h = np.maximum(w1 @ h + b1, 0)
    z = w2 @ h + b2
    e = np.exp(z - z.max())
    return e / e.sum()


def write_f32_header(layers, path):
    def arr(name, a):
        vals = ", ".join(f"{v:.8e}f" for v in a.ravel())
        return f"static const float {name}[{a.size}] = {{{vals}}};\n"

    out = ["// Generated by ml/export.py -- do not edit.\n#pragma once\n\n"
           "#define MODEL_F32_AVAILABLE 1\n\n"]
    for i, (w, b) in enumerate(layers["convs"], start=1):
        out.append(f"constexpr int kC{i}Out = {w.shape[0]};\n"
                   f"constexpr int kC{i}K = {w.shape[1]};\n")
        out.append(arr(f"kC{i}W", w) + arr(f"kC{i}B", b))
    (w1, b1), (w2, b2) = layers["denses"]
    out.append(f"constexpr int kD1Out = {w1.shape[0]};\n")
    out.append(arr("kD1W", w1) + arr("kD1B", b1) + arr("kD2W", w2) + arr("kD2B", b2))
    path.write_text("".join(out))


if __name__ == "__main__":
    main()
