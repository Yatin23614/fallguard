# PlatformIO pre-build script: gzips ../web/index.html into src/web_index.h so
# the ESP32 can serve the dashboard. Runs on every build; only rewrites the
# header when the page changed (keeps incremental builds fast).
import gzip
from pathlib import Path

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    root = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:  # run directly: python embed_web.py
    root = Path(__file__).resolve().parent

src = root.parent / "web" / "index.html"
out = root / "src" / "web_index.h"

data = gzip.compress(src.read_bytes(), compresslevel=9, mtime=0)
rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
text = (
    "// Generated by firmware/embed_web.py from web/index.html -- do not edit.\n"
    "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
    f"static const uint8_t kWebIndexGz[{len(data)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
    f"static const size_t kWebIndexGzLen = {len(data)};\n"
)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
    print(f"embed_web: {src.name} -> {out.name} ({len(data)} bytes gzipped)")
